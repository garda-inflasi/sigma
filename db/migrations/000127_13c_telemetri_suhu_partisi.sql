-- Slice 13-C (docs/todos/13-cold-storage.md): konversi telemetri_suhu menjadi tabel berpartisi bulanan
-- (PARTITION BY RANGE (waktu)) dengan fungsi pemeliharaan partisi otomatis, mempertahankan seluruh FK dan indeks.
-- Hak garda_aplikasi (000119) diberikan pada level skema (ALL TABLES), sehingga partisi baru otomatis terjangkau.

-- +goose Up
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION pastikan_partisi_telemetri_suhu(bulan_target DATE)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    awal_bulan TIMESTAMPTZ := (date_trunc('month', bulan_target)::timestamp AT TIME ZONE 'UTC');
    akhir_bulan TIMESTAMPTZ := ((date_trunc('month', bulan_target) + INTERVAL '1 month')::timestamp AT TIME ZONE 'UTC');
    nama_partisi TEXT := format('telemetri_suhu_y%sm%s', to_char(bulan_target, 'YYYY'), to_char(bulan_target, 'MM'));
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS %I PARTITION OF telemetri_suhu FOR VALUES FROM (%L) TO (%L)',
        nama_partisi, awal_bulan, akhir_bulan
    );
    RETURN nama_partisi;
END;
$$;

ALTER TABLE telemetri_suhu RENAME TO telemetri_suhu_lama;

CREATE TABLE telemetri_suhu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fasilitas_id UUID NOT NULL REFERENCES cold_storage(id) ON DELETE CASCADE,
    waktu TIMESTAMPTZ NOT NULL,
    suhu_c DOUBLE PRECISION NOT NULL CHECK (suhu_c BETWEEN -80 AND 60),
    kelembapan_pct DOUBLE PRECISION CHECK (kelembapan_pct BETWEEN 0 AND 100),
    sumber VARCHAR(10) NOT NULL DEFAULT 'SENSOR' CHECK (sumber IN ('SENSOR', 'MANUAL', 'DEMO')),
    PRIMARY KEY (id, waktu),
    UNIQUE (fasilitas_id, waktu)
) PARTITION BY RANGE (waktu);

CREATE INDEX idx_telemetri_suhu_fasilitas_waktu ON telemetri_suhu (fasilitas_id, waktu DESC);
CREATE INDEX idx_telemetri_suhu_waktu ON telemetri_suhu USING brin (waktu) WITH (pages_per_range = 32);

DO $$
DECLARE
    r RECORD;
BEGIN
    -- Buat partisi bulan berjalan dan bulan berikutnya.
    PERFORM pastikan_partisi_telemetri_suhu(date_trunc('month', CURRENT_DATE)::date);
    PERFORM pastikan_partisi_telemetri_suhu((date_trunc('month', CURRENT_DATE) + INTERVAL '1 month')::date);

    -- Buat partisi untuk seluruh bulan historis yang sudah ada di data lama sebelum partisi DEFAULT dibuat.
    FOR r IN
        SELECT DISTINCT date_trunc('month', waktu AT TIME ZONE 'UTC')::date AS bulan
        FROM telemetri_suhu_lama
    LOOP
        PERFORM pastikan_partisi_telemetri_suhu(r.bulan);
    END LOOP;
END $$;

CREATE TABLE telemetri_suhu_default PARTITION OF telemetri_suhu DEFAULT;

INSERT INTO telemetri_suhu (id, fasilitas_id, waktu, suhu_c, kelembapan_pct, sumber)
SELECT id, fasilitas_id, waktu, suhu_c, kelembapan_pct, sumber
FROM telemetri_suhu_lama;

SELECT setval(
    pg_get_serial_sequence('telemetri_suhu', 'id'),
    COALESCE((SELECT MAX(id) FROM telemetri_suhu), 1),
    EXISTS (SELECT 1 FROM telemetri_suhu)
);

DROP TABLE telemetri_suhu_lama;
-- +goose StatementEnd

