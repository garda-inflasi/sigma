#!/usr/bin/env bash
# ==============================================================================
#  Garda Inflasi — scripts/deploy/init-server.sh
#  Idempotent VM bootstrap:
#    1. Adds VM_USER to the `docker` group so deploy commands run without sudo.
#    2. Prepares /home/ubuntu/garda-inflasi directory layout & permissions.
#    3. Verifies external Caddy gateway & network (when GATEWAY_MODE=external).
#    4. Generates production .env (if missing) with strong random secrets.
#
#  Usage:
#      bash scripts/deploy/init-server.sh [--dry-run]
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
source "${SCRIPT_DIR}/../lib/common.sh"
# shellcheck source=../lib/ssh-wrapper.sh
source "${SCRIPT_DIR}/../lib/ssh-wrapper.sh"

install_traps

DRY_RUN="${DRY_RUN:-0}"

usage() {
  sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "Opsi tidak dikenal: $1" "Jalankan 'bash scripts/deploy/init-server.sh --help'." ;;
  esac
  shift
done

export DRY_RUN

load_env_deploy
validate_ssh_key

log_section "Bootstrap VM — ${VM_USER}@${VM_HOST}:${SSH_PORT}"
print_kv "Remote dir"   "$REMOTE_DIR"
print_kv "Gateway mode" "$GATEWAY_MODE"
print_kv "Public host"  "$PUBLIC_HOST"

# 1. Verify SSH connectivity
if [[ "$DRY_RUN" == "1" ]]; then
  echo_cmd "ssh ${VM_USER}@${VM_HOST} 'true'"
else
  if ! vm_ssh "true" >/dev/null 2>&1; then
    die "Gagal koneksi SSH ke ${VM_USER}@${VM_HOST}:${SSH_PORT}." \
        "Periksa IP, username, password/key di .env.deploy."
  fi
  log_success "Koneksi SSH OK."
fi

# 2. Ensure user is in docker group
log_info "Memeriksa akses grup docker untuk '${VM_USER}' ..."
if [[ "$DRY_RUN" == "1" ]]; then
  echo_cmd "vm_ssh_sudo 'usermod -aG docker ${VM_USER}'"
else
  if vm_ssh "id -nG '${VM_USER}' | grep -qw docker" >/dev/null 2>&1; then
    log_success "User '${VM_USER}' sudah tergabung di grup docker."
  else
    log_warn "User '${VM_USER}' belum di grup docker — menambahkan via sudo ..."
    vm_ssh_sudo "usermod -aG docker '${VM_USER}'"
    # Note: new SSH sessions pick up group membership immediately.
    if vm_ssh "docker info >/dev/null 2>&1"; then
      log_success "Akses Docker aktif untuk '${VM_USER}'."
    else
      die "Gagal memverifikasi akses Docker setelah usermod." \
          "Coba restart docker socket atau login ulang di VM: sudo systemctl restart docker"
    fi
  fi
fi

# 3. Create remote directories
log_info "Menyiapkan direktori aplikasi di ${REMOTE_DIR} ..."
vm_ssh "mkdir -p '${REMOTE_DIR}'/{compose,dist,scripts,backups,data/uploads,logs,docker/postgres,db/migrations} && chmod 750 '${REMOTE_DIR}' && chmod 700 '${REMOTE_DIR}/backups'"
log_success "Struktur direktori di ${REMOTE_DIR} siap."

# 4. Verify external Caddy gateway
if [[ "$GATEWAY_MODE" == "external" ]]; then
  log_info "Memeriksa Caddy gateway existing (${GATEWAY_CADDY_DIR}, network=${GATEWAY_NETWORK}) ..."
  if [[ "$DRY_RUN" == "1" ]]; then
    echo_cmd "vm_ssh 'test -d ${GATEWAY_CADDY_DIR} && docker network inspect ${GATEWAY_NETWORK}'"
  else
    if ! vm_ssh "test -d '${GATEWAY_CADDY_DIR}'"; then
      die "Direktori Caddy gateway tidak ditemukan: ${GATEWAY_CADDY_DIR}" \
          "Sesuaikan GATEWAY_CADDY_DIR di .env.deploy atau ubah GATEWAY_MODE=builtin."
    fi
    if ! vm_ssh "docker network inspect '${GATEWAY_NETWORK}' >/dev/null 2>&1"; then
      die "Network Docker gateway '${GATEWAY_NETWORK}' belum ada." \
          "Pastikan stack Caddy di ${GATEWAY_CADDY_DIR} sedang berjalan."
    fi
    log_success "Caddy gateway & network '${GATEWAY_NETWORK}' ditemukan."
  fi
fi

# 5. Generate production .env if absent (never overwrite existing!)
log_info "Memeriksa ${REMOTE_DIR}/.env ..."
if [[ "$DRY_RUN" == "1" ]]; then
  echo_cmd "vm_ssh 'test -f ${REMOTE_DIR}/.env || generate production .env'"
else
  if vm_ssh "test -f '${REMOTE_DIR}/.env'"; then
    log_success "File ${REMOTE_DIR}/.env sudah ada (tidak ditimpa)."
  else
    log_warn "${REMOTE_DIR}/.env belum ada — membuat konfigurasi produksi dengan rahasia acak ..."
    public_origin="https://${PUBLIC_HOST}"
    vm_ssh "umask 077 && cat > '${REMOTE_DIR}/.env' <<EOF
# Garda Inflasi — Production Environment (VM)
# Generated by init-server.sh on \$(date -u +%Y-%m-%dT%H:%M:%SZ)

APP_ENV=production
GIN_MODE=release
APP_PUBLIC_URL=${public_origin}
APP_ALLOWED_ORIGINS=${public_origin}

# Database (PostgreSQL)
POSTGRES_DB=garda_inflasi
POSTGRES_USER=garda
POSTGRES_PASSWORD=\$(openssl rand -hex 24)
POSTGRES_PORT=5432
DB_APP_USER=garda_app
DB_APP_PASSWORD=\$(openssl rand -hex 24)

# Security Secrets (wajib unik & kuat; AES_KEY tepat 32 byte)
JWT_SECRET=\$(openssl rand -hex 32)
AES_KEY=\$(openssl rand -hex 16)

# Redis
REDIS_PORT=6379

# MongoDB & Pipeline Data/ML (crawler -> dataunseen, ml-worker -> datasafe)
MONGO_USER=garda
MONGO_PASSWORD=\$(openssl rand -hex 24)
MONGO_DB=garda_inflasi
MONGO_PORT=27017
MONGO_VOLUME=garda_pipeline_mongo_data
MONGO_DB_UNSEEN=dataunseen
MONGO_DB_SAFE=datasafe
ML_N_JOBS=4
ML_INTERVAL_SELEKSI_JAM=24

# Seed admin awal (dipakai cmd/seed admin saat tabel pengguna kosong)
SEED_ADMIN_EMAIL=admin@gardainflasi.id
SEED_ADMIN_PASSWORD=\$(openssl rand -base64 18 | tr -d '/+=')

# Penyimpanan lampiran lapangan
LAPANGAN_UPLOAD_DIR=/app/uploads

# Layanan ML internal & scheduler
ML_SERVICE_URL=http://ml:8000
EWS_EVAL_INTERVAL=15m
JOB_SIKLUS_EVALUASI_INTERVAL=5m
EWS_NOTIF_INTERVAL=30s
JOB_DASHBOARD_REFRESH_INTERVAL=5m
JOB_KPI_HITUNG_INTERVAL=1h
JOB_PREDIKSI_RETRAIN_INTERVAL=168h
INGEST_SCHEDULER=
EOF
chmod 600 '${REMOTE_DIR}/.env'"
    log_success "File ${REMOTE_DIR}/.env dibuat (mode 600)."
  fi

  # Initialize .env.tags if missing
  if ! vm_ssh "test -f '${REMOTE_DIR}/.env.tags'"; then
    vm_ssh "cat > '${REMOTE_DIR}/.env.tags' <<EOF
IMAGE_TAG=latest
API_IMAGE_TAG=latest
WEB_IMAGE_TAG=latest
ML_IMAGE_TAG=latest
ML_PIPELINE_IMAGE_TAG=latest
CRAWLER_IMAGE_TAG=latest
EOF"
    log_success "File ${REMOTE_DIR}/.env.tags diinisialisasi."
  fi
fi

log_success "Bootstrap server selesai."
